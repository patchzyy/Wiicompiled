using System.Text;
using Translator.Core.CodeGen;
using Translator.Core.IO;
using Translator.Core.Parsing.Kamek;
using Translator.Core.Mods.Mkwii;

namespace Translator.Core.Mods;

public static class ModDataPatchWriter
{
    public static void Write(
        string path,
        KamekPatchPlan patchPlan,
        uint moduleLinkBase,
        BaseManifest baseManifest,
        IReadOnlyList<string> dvdOverlayRoots,
        byte[] relocatedModuleImage,
        byte[]? sourceKamekCodeSha1Digest,
        IReadOnlyCollection<RetroWfcStaticPointerPlan>? retroWfcStaticPointers,
        uint moduleBssOffset,
        uint moduleBssSize,
        uint ctorStart,
        uint ctorEnd,
        bool emitCtorRunner,
        uint? retroWfcInitializerAddress = null,
        uint? retroWfcInitializerPayloadBase = null,
        uint? retroWfcInitializerSuccessReturnValue = null,
        string? publishedBlobDirectory = null,
        string? riivolutionXml = null,
        IReadOnlyList<ModRiivolutionOption>? riivolutionOptions = null)
    {
        var blobAssemblyPath = Path.Combine(
            Path.GetDirectoryName(path) ?? ".",
            Path.GetFileNameWithoutExtension(path) + "_blobs.S");
        var blobDirectory = Path.Combine(
            Path.GetDirectoryName(path) ?? ".",
            Path.GetFileNameWithoutExtension(path) + "_blobs");
        var blobs = new List<ModDataBlob>
        {
            new("kModuleImage", "module_image.bin", relocatedModuleImage),
        };
        if (sourceKamekCodeSha1Digest is { Length: 20 })
        {
            blobs.Add(new ModDataBlob("kKamekCodeSha1Digest", "kamek_code_sha1.bin", sourceKamekCodeSha1Digest));
        }
        WriteBlobFiles(
            blobAssemblyPath,
            blobDirectory,
            publishedBlobDirectory ?? blobDirectory,
            blobs);

        var sb = new StringBuilder();
        var emitRetroWfcInitializer =
            retroWfcInitializerAddress.HasValue &&
            retroWfcInitializerPayloadBase.HasValue &&
            retroWfcInitializerSuccessReturnValue.HasValue;
        sb.AppendLine("// Generated by translator translate-mod.");
        sb.AppendLine("#include \"abi_bridge.h\"");
        sb.AppendLine("#include \"memory.h\"");
        sb.AppendLine("#include \"recomp_mod_loader.h\"");
        sb.AppendLine();
        sb.AppendLine("#include <cstdint>");
        sb.AppendLine("#include <cstring>");
        sb.AppendLine("#include <iostream>");
        sb.AppendLine();
        sb.AppendLine("extern \"C\" {");
        foreach (var blob in blobs)
        {
            sb.AppendLine($"extern const uint8_t {blob.Symbol}[];");
        }
        sb.AppendLine("} // extern \"C\"");
        sb.AppendLine();
        sb.AppendLine("namespace {");
        sb.AppendLine();
        sb.AppendLine($"constexpr uint32_t kModuleGuestBase = 0x{patchPlan.ModuleGuestBase:X8}u;");
        sb.AppendLine($"constexpr uint32_t kModuleImageSize = 0x{relocatedModuleImage.Length:X8}u;");
        sb.AppendLine($"constexpr uint32_t kModuleBssOffset = 0x{moduleBssOffset:X8}u;");
        sb.AppendLine($"constexpr uint32_t kModuleBssSize = 0x{moduleBssSize:X8}u;");
        sb.AppendLine("constexpr uint32_t kModuleBssEnd = kModuleBssOffset + kModuleBssSize;");
        sb.AppendLine("constexpr uint32_t kModuleReservedSize = kModuleImageSize > kModuleBssEnd ? kModuleImageSize : kModuleBssEnd;");
        sb.AppendLine($"constexpr uint32_t kCtorStart = 0x{ctorStart:X8}u;");
        sb.AppendLine($"constexpr uint32_t kCtorEnd = 0x{ctorEnd:X8}u;");
        if (emitRetroWfcInitializer)
        {
            sb.AppendLine($"constexpr uint32_t kRetroWfcInitializerAddress = 0x{retroWfcInitializerAddress!.Value:X8}u;");
            sb.AppendLine($"constexpr uint32_t kRetroWfcInitializerPayloadBase = 0x{retroWfcInitializerPayloadBase!.Value:X8}u;");
            sb.AppendLine($"constexpr uint32_t kRetroWfcInitializerSuccessReturnValue = 0x{retroWfcInitializerSuccessReturnValue!.Value:X8}u;");
        }
        sb.AppendLine("constexpr uint32_t kModuleReservedEnd = kModuleGuestBase + kModuleReservedSize;");
        sb.AppendLine();
        sb.AppendLine("void InitializeModuleImage() {");
        sb.AppendLine("    std::memcpy(Memory::GetPointer(kModuleGuestBase, kModuleImageSize), kModuleImage, kModuleImageSize);");
        sb.AppendLine("    if (kModuleBssSize != 0) {");
        sb.AppendLine("        std::memset(Memory::GetPointer(kModuleGuestBase + kModuleBssOffset, kModuleBssSize), 0, kModuleBssSize);");
        sb.AppendLine("    }");
        if (sourceKamekCodeSha1Digest is { Length: 20 })
        {
            sb.AppendLine("    std::memcpy(Memory::GetPointer(0x800017B0u, 20u), kKamekCodeSha1Digest, 20u);");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        EmitStaticPatchHelpers(sb);
        sb.AppendLine();
        sb.AppendLine("void RegisterExecutableRanges() {");
        var knownFunctionsBySection = baseManifest.Functions
            .Where(f => f.End > f.Start && f.Flags.Contains("HasKnownTranslation"))
            .GroupBy(f => f.SourceSection)
            .ToDictionary(g => g.Key, g => g.OrderBy(f => f.Start).First());
        foreach (var section in baseManifest.Sections
                     .Where(s => s.Executable && s.GuestEnd > s.GuestStart)
                     .OrderBy(s => s.GuestStart))
        {
            var guardedStart = knownFunctionsBySection.TryGetValue(section.Name, out var firstFunction)
                ? firstFunction.Start
                : section.GuestStart;
            if (guardedStart >= section.GuestEnd)
            {
                continue;
            }

            var name = $"{section.Source}:{section.Name}";
            sb.AppendLine(
                $"    RecompMod::RegisterExecutableRange(0x{guardedStart:X8}u, 0x{section.GuestEnd:X8}u, \"{EscapeCxxStringLiteral(name)}\");");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void ApplyExecutableBasePatches() {");
        foreach (var patch in patchPlan.ExecutablePatches.OrderBy(p => p.CommandAddress))
        {
            EmitBaseExecutablePatch(sb, patch, moduleLinkBase);
        }
        sb.AppendLine("}");
        sb.AppendLine();
        if (emitCtorRunner)
        {
            sb.AppendLine("void RunCtors() {");
            sb.AppendLine("    InitializePersistentCpuContext();");
            sb.AppendLine("    CpuContext& cpu = GetPersistentCpuContext();");
            sb.AppendLine("    for (uint32_t ptr = kCtorStart; ptr + 4 <= kCtorEnd; ptr += 4) {");
            sb.AppendLine("        const uint32_t ctor = Memory::Read32(ptr);");
            sb.AppendLine("        if (ctor != 0) {");
            sb.AppendLine("            InvokeIndirectCpu(ctor, &cpu);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }
        if (emitRetroWfcInitializer)
        {
            sb.AppendLine("void RunRetroWfcInitializer() {");
            sb.AppendLine("    InitializePersistentCpuContext();");
            sb.AppendLine("    CpuContext& cpu = GetPersistentCpuContext();");
            sb.AppendLine("    cpu.gpr[3] = kRetroWfcInitializerPayloadBase;");
            sb.AppendLine("    InvokeIndirectCpu(kRetroWfcInitializerAddress, &cpu);");
            sb.AppendLine("    if (cpu.gpr[3] != kRetroWfcInitializerSuccessReturnValue) {");
            sb.AppendLine("        std::cerr << \"[mod] FATAL Retro WFC helper initialization failed: result=0x\" << std::hex << cpu.gpr[3]");
            sb.AppendLine("                  << \" expected=0x\" << kRetroWfcInitializerSuccessReturnValue << std::dec << std::endl;");
            sb.AppendLine("        std::abort();");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }
        sb.AppendLine("void ApplyDataPatches() {");
        sb.AppendLine("    InitializeModuleImage();");
        sb.AppendLine("    ApplyExecutableBasePatches();");
        foreach (var patch in patchPlan.DataPatches.OrderBy(p => p.CommandAddress))
        {
            EmitPatch(sb, patch, patchPlan.ModuleGuestBase);
        }
        foreach (var pointer in (retroWfcStaticPointers ?? Array.Empty<RetroWfcStaticPointerPlan>())
                     .Where(p => !p.SectionExecutable && p.TargetAddress.HasValue)
                     .OrderBy(p => p.Address)
                     .ThenBy(p => p.RecordIndex))
        {
            sb.AppendLine($"    Memory::Write32(0x{pointer.Address:X8}u, 0x{pointer.TargetAddress!.Value:X8}u); // Retro WFC {EscapeCxxStringLiteral(pointer.TargetActionId ?? string.Join(",", pointer.SemanticActionIds))}");
        }
        sb.AppendLine("    RegisterExecutableRanges();");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("struct RegisterModDataPatches {");
        sb.AppendLine("    RegisterModDataPatches() {");
        sb.AppendLine("        RecompMod::RegisterMemoryReservation(kModuleGuestBase, kModuleReservedEnd, \"Kamek module\");");
        sb.AppendLine("        RecompMod::RegisterMemoryInitializer(&ApplyDataPatches);");
        if (emitCtorRunner)
        {
            sb.AppendLine("        RecompMod::RegisterPostRelInitializer(&RunCtors);");
        }
        if (emitRetroWfcInitializer)
        {
            sb.AppendLine("        RecompMod::RegisterPostRelInitializer(&RunRetroWfcInitializer);");
        }
        foreach (var root in dvdOverlayRoots)
        {
            sb.AppendLine($"        RecompMod::RegisterDvdOverlayRoot(\"{EscapeCxxStringLiteral(root)}\");");
        }
        if (!string.IsNullOrWhiteSpace(riivolutionXml))
        {
            sb.AppendLine($"        RecompMod::RegisterRiivolutionXml(\"{EscapeCxxStringLiteral(riivolutionXml)}\");");
        }
        foreach (var option in riivolutionOptions ?? [])
        {
            sb.AppendLine(
                $"        RecompMod::RegisterRiivolutionOption(\"{EscapeCxxStringLiteral(option.Section)}\", \"{EscapeCxxStringLiteral(option.Option)}\", {option.Choice}u);");
        }
        sb.AppendLine("    }");
        sb.AppendLine("};");
        sb.AppendLine();
        sb.AppendLine("RegisterModDataPatches g_registerModDataPatches;");
        sb.AppendLine();
        sb.AppendLine("} // namespace");

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        FileOutput.WriteTextIfChanged(path, sb.ToString());
    }

    private static void WriteBlobFiles(
        string assemblyPath,
        string blobDirectory,
        string blobReferenceDirectory,
        IReadOnlyList<ModDataBlob> blobs)
    {
        var assemblyBlobs = blobs.Select(blob => new AssemblyBlob(
            blob.FileName,
            blob.Symbol,
            blob.Data,
            $"{blob.FileName}: {blob.Data.Length} bytes"))
            .ToList();
        AssemblyBlobWriter.Write(
            assemblyPath,
            blobDirectory,
            blobReferenceDirectory,
            assemblyBlobs,
            "// Generated by translator translate-mod.",
            "// Binary payloads referenced by mod_data_patches.cpp.");
    }

    private sealed record ModDataBlob(string Symbol, string FileName, byte[] Data);

    private static void EmitStaticPatchHelpers(StringBuilder sb)
    {
        sb.AppendLine("void PatchGuestU8(uint32_t address, uint32_t value) {");
        sb.AppendLine("    auto* ptr = Memory::GetPointer(address, 1);");
        sb.AppendLine("    ptr[0] = static_cast<uint8_t>(value);");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void PatchGuestU16(uint32_t address, uint32_t value) {");
        sb.AppendLine("    auto* ptr = Memory::GetPointer(address, 2);");
        sb.AppendLine("    ptr[0] = static_cast<uint8_t>((value >> 8) & 0xFFu);");
        sb.AppendLine("    ptr[1] = static_cast<uint8_t>(value & 0xFFu);");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void PatchGuestU32(uint32_t address, uint32_t value) {");
        sb.AppendLine("    auto* ptr = Memory::GetPointer(address, 4);");
        sb.AppendLine("    ptr[0] = static_cast<uint8_t>((value >> 24) & 0xFFu);");
        sb.AppendLine("    ptr[1] = static_cast<uint8_t>((value >> 16) & 0xFFu);");
        sb.AppendLine("    ptr[2] = static_cast<uint8_t>((value >> 8) & 0xFFu);");
        sb.AppendLine("    ptr[3] = static_cast<uint8_t>(value & 0xFFu);");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("bool EncodeStaticPpcBranch(uint32_t from, uint32_t to, bool link, uint32_t& instruction) {");
        sb.AppendLine("    const int32_t delta = static_cast<int32_t>(to) - static_cast<int32_t>(from);");
        sb.AppendLine("    if ((delta & 0x3) != 0 || delta < -0x02000000 || delta > 0x01FFFFFC) {");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine("    instruction = 0x48000000u | (static_cast<uint32_t>(delta) & 0x03FFFFFCu) | (link ? 1u : 0u);");
        sb.AppendLine("    return true;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void FatalStaticPatchRange(uint32_t address, uint32_t target) {");
        sb.AppendLine("    std::cerr << \"[mod] FATAL static executable branch target out of range\" << std::endl;");
        sb.AppendLine("    std::cerr << \"  address: 0x\" << std::hex << address << std::endl;");
        sb.AppendLine("    std::cerr << \"  target:  0x\" << target << std::dec << std::endl;");
        sb.AppendLine("    std::abort();");
        sb.AppendLine("}");
    }

    private static void EmitBaseExecutablePatch(StringBuilder sb, KamekPatchClassification patch, uint moduleLinkBase)
    {
        var address = patch.CommandAddress;
        switch (patch.CommandId)
        {
            case KamekCommandId.Addr32:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase);
                sb.AppendLine($"    PatchGuestU32(0x{address:X8}u, 0x{value:X8}u);");
                return;
            }
            case KamekCommandId.Addr16Lo:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase) & 0xFFFFu;
                sb.AppendLine($"    PatchGuestU16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Addr16Hi:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase) >> 16;
                sb.AppendLine($"    PatchGuestU16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Addr16Ha:
            {
                var value = (KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase) + 0x8000u) >> 16;
                sb.AppendLine($"    PatchGuestU16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Rel24:
            {
                var target = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase);
                sb.AppendLine("    {");
                sb.AppendLine($"        const uint32_t address = 0x{address:X8}u;");
                sb.AppendLine($"        const uint32_t target = 0x{target:X8}u;");
                sb.AppendLine("        const uint32_t original = Memory::Read32(address);");
                sb.AppendLine("        const int32_t delta = static_cast<int32_t>(target) - static_cast<int32_t>(address);");
                sb.AppendLine("        if ((delta & 0x3) != 0 || delta < -0x02000000 || delta > 0x01FFFFFC) {");
                sb.AppendLine("            FatalStaticPatchRange(address, target);");
                sb.AppendLine("        }");
                sb.AppendLine("        PatchGuestU32(address, (original & 0xFC000003u) | (static_cast<uint32_t>(delta) & 0x03FFFFFCu));");
                sb.AppendLine("    }");
                return;
            }
            case KamekCommandId.Write32:
                sb.AppendLine($"    PatchGuestU32(0x{address:X8}u, 0x{patch.Arguments[0]:X8}u);");
                return;
            case KamekCommandId.Write16:
                sb.AppendLine($"    PatchGuestU16(0x{address:X8}u, 0x{patch.Arguments[0] & 0xFFFFu:X4}u);");
                return;
            case KamekCommandId.Write8:
                sb.AppendLine($"    PatchGuestU8(0x{address:X8}u, 0x{patch.Arguments[0] & 0xFFu:X2}u);");
                return;
            case KamekCommandId.CondWritePointer:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase);
                EmitConditionalShadowWrite32(sb, address, patch.Arguments[1], value);
                return;
            }
            case KamekCommandId.CondWrite32:
                EmitConditionalShadowWrite32(sb, address, patch.Arguments[1], patch.Arguments[0]);
                return;
            case KamekCommandId.CondWrite16:
                EmitConditionalShadowWrite16(sb, address, patch.Arguments[1], patch.Arguments[0]);
                return;
            case KamekCommandId.CondWrite8:
                EmitConditionalShadowWrite8(sb, address, patch.Arguments[1], patch.Arguments[0]);
                return;
            case KamekCommandId.Branch:
            case KamekCommandId.BranchLink:
            {
                var target = KamekAddress.Resolve(patch.Arguments[0], moduleLinkBase);
                sb.AppendLine("    {");
                sb.AppendLine($"        uint32_t instruction = 0;");
                sb.AppendLine($"        if (!EncodeStaticPpcBranch(0x{address:X8}u, 0x{target:X8}u, {(patch.CommandId == KamekCommandId.BranchLink ? "true" : "false")}, instruction)) {{");
                sb.AppendLine($"            FatalStaticPatchRange(0x{address:X8}u, 0x{target:X8}u);");
                sb.AppendLine("        }");
                sb.AppendLine($"        PatchGuestU32(0x{address:X8}u, instruction);");
                sb.AppendLine("    }");
                return;
            }
            default:
                throw new InvalidDataException($"Cannot emit executable shadow patch for {patch.CommandId} at 0x{address:X8}.");
        }
    }

    private static void EmitPatch(StringBuilder sb, KamekPatchClassification patch, uint moduleGuestBase)
    {
        var address = patch.CommandAddress;
        switch (patch.CommandId)
        {
            case KamekCommandId.Addr32:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleGuestBase);
                sb.AppendLine($"    Memory::Write32(0x{address:X8}u, 0x{value:X8}u);");
                return;
            }
            case KamekCommandId.Addr16Lo:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleGuestBase) & 0xFFFFu;
                sb.AppendLine($"    Memory::Write16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Addr16Hi:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleGuestBase) >> 16;
                sb.AppendLine($"    Memory::Write16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Addr16Ha:
            {
                var value = (KamekAddress.Resolve(patch.Arguments[0], moduleGuestBase) + 0x8000u) >> 16;
                sb.AppendLine($"    Memory::Write16(0x{address:X8}u, 0x{value:X4}u);");
                return;
            }
            case KamekCommandId.Write32:
                sb.AppendLine($"    Memory::Write32(0x{address:X8}u, 0x{patch.Arguments[0]:X8}u);");
                return;
            case KamekCommandId.Write16:
                sb.AppendLine($"    Memory::Write16(0x{address:X8}u, 0x{patch.Arguments[0] & 0xFFFFu:X4}u);");
                return;
            case KamekCommandId.Write8:
                sb.AppendLine($"    Memory::Write8(0x{address:X8}u, 0x{patch.Arguments[0] & 0xFFu:X2}u);");
                return;
            case KamekCommandId.CondWritePointer:
            {
                var value = KamekAddress.Resolve(patch.Arguments[0], moduleGuestBase);
                EmitConditionalWrite32(sb, address, patch.Arguments[1], value);
                return;
            }
            case KamekCommandId.CondWrite32:
                EmitConditionalWrite32(sb, address, patch.Arguments[1], patch.Arguments[0]);
                return;
            case KamekCommandId.CondWrite16:
                EmitConditionalWrite16(sb, address, patch.Arguments[1] & 0xFFFFu, patch.Arguments[0] & 0xFFFFu);
                return;
            case KamekCommandId.CondWrite8:
                EmitConditionalWrite8(sb, address, patch.Arguments[1] & 0xFFu, patch.Arguments[0] & 0xFFu);
                return;
            default:
                throw new InvalidDataException($"Cannot emit data patch for {patch.CommandId} at 0x{address:X8}.");
        }
    }

    private static void EmitConditionalWrite32(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read32(0x{address:X8}u) == 0x{expected:X8}u) {{");
        sb.AppendLine($"        Memory::Write32(0x{address:X8}u, 0x{value:X8}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped CondWrite32 at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static void EmitConditionalWrite16(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read16(0x{address:X8}u) == 0x{expected:X4}u) {{");
        sb.AppendLine($"        Memory::Write16(0x{address:X8}u, 0x{value:X4}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped CondWrite16 at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static void EmitConditionalWrite8(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read8(0x{address:X8}u) == 0x{expected:X2}u) {{");
        sb.AppendLine($"        Memory::Write8(0x{address:X8}u, 0x{value:X2}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped CondWrite8 at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static void EmitConditionalShadowWrite32(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read32(0x{address:X8}u) == 0x{expected:X8}u) {{");
        sb.AppendLine($"        PatchGuestU32(0x{address:X8}u, 0x{value:X8}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped executable CondWrite32 shadow patch at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static void EmitConditionalShadowWrite16(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read16(0x{address:X8}u) == 0x{expected & 0xFFFFu:X4}u) {{");
        sb.AppendLine($"        PatchGuestU16(0x{address:X8}u, 0x{value & 0xFFFFu:X4}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped executable CondWrite16 shadow patch at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static void EmitConditionalShadowWrite8(StringBuilder sb, uint address, uint expected, uint value)
    {
        sb.AppendLine($"    if (Memory::Read8(0x{address:X8}u) == 0x{expected & 0xFFu:X2}u) {{");
        sb.AppendLine($"        PatchGuestU8(0x{address:X8}u, 0x{value & 0xFFu:X2}u);");
        sb.AppendLine("    } else {");
        sb.AppendLine($"        std::cerr << \"[mod] Skipped executable CondWrite8 shadow patch at 0x{address:X8}\" << std::endl;");
        sb.AppendLine("    }");
    }

    private static string EscapeCxxStringLiteral(string value) => CxxStringLiteralEscaping.Escape(value);
}

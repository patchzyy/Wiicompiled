std::string Hex32(uint32_t value) {
    std::ostringstream oss;
    oss << std::hex << std::uppercase << std::setw(8) << std::setfill('0') << value;
    return oss.str();
}

std::optional<std::string> PrintableU32(uint32_t value) {
    std::string out;
    out.reserve(4);
    for (int shift = 24; shift >= 0; shift -= 8) {
        const auto ch = static_cast<unsigned char>((value >> shift) & 0xFFu);
        if (!std::isprint(ch)) {
            return std::nullopt;
        }
        out.push_back(static_cast<char>(ch));
    }
    return out;
}

std::optional<TranslatedFunctionInfo> FindNearestTranslatedFunction(uint32_t address) {
    auto best = TranslatedFunctionRegistry::FindNearestByAddress(address);

    // Crash-only heuristic: large gaps are usually data/FourCC values, not code offsets.
    if (best && address - best->address < 0x10000u) {
        return best;
    }
    return std::nullopt;
}

// generated/guest_symbol_table.cpp (or the stub when it is absent): the
// project's function-map names, sorted by address, for crash symbolization.
extern "C" {
extern const uint32_t kGuestMapSymbolCount;
extern const uint32_t kGuestMapSymbolAddresses[];
extern const char* const kGuestMapSymbolNames[];
}

// Floor lookup into the function-map name table with the same gap cap as the
// registry heuristic above. Returns nullptr when no named symbol is close.
const char* GuestMapSymbolFloor(uint32_t address, uint32_t* symbolStart) {
    if (kGuestMapSymbolCount == 0) {
        return nullptr;
    }
    uint32_t lo = 0;
    uint32_t hi = kGuestMapSymbolCount;
    while (lo < hi) {
        const uint32_t mid = lo + (hi - lo) / 2;
        if (kGuestMapSymbolAddresses[mid] <= address) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if (lo == 0) {
        return nullptr;
    }
    const uint32_t index = lo - 1;
    if (address - kGuestMapSymbolAddresses[index] >= 0x10000u) {
        return nullptr;
    }
    if (symbolStart) {
        *symbolStart = kGuestMapSymbolAddresses[index];
    }
    return kGuestMapSymbolNames[index];
}

std::optional<uint32_t> ReadGuest32NoThrow(uint32_t address) {
    uint32_t value = 0;
    if (MemoryInline::TryReadMappedScalar(address, value)) {
        return value;
    }
    return std::nullopt;
}

std::optional<uint8_t> ReadGuest8NoThrow(uint32_t address) {
    uint8_t value = 0;
    if (MemoryInline::TryReadMappedScalar(address, value)) {
        return value;
    }
    return std::nullopt;
}

std::optional<std::string> GuestCStringPreview(uint32_t address) {
    std::string out;
    out.reserve(48);
    for (uint32_t i = 0; i < 48; ++i) {
        const auto byte = ReadGuest8NoThrow(address + i);
        if (!byte) {
            return std::nullopt;
        }
        if (*byte == 0) {
            return out.size() >= 3 ? std::optional<std::string>(out) : std::nullopt;
        }
        if (!std::isprint(*byte)) {
            return std::nullopt;
        }
        out.push_back(static_cast<char>(*byte));
    }
    out += "...";
    return out;
}

void PrintGuestValue(std::ostream& os, std::string_view label, uint32_t value) {
    os << " ";
    if (!label.empty()) {
        os << label << "=";
    }
    os << "0x" << Hex32(value);
    // Prefer the function-map name (human symbol) over the registry's
    // func_XXXXXXXX label; when both resolve, the closer floor wins so a map
    // symbol from a preceding function cannot shadow an exact registry hit.
    uint32_t mapStart = 0;
    const char* mapName = GuestMapSymbolFloor(value, &mapStart);
    if (const auto* exact = TranslatedFunctionRegistry::FindByAddressPtr(value)) {
        if (mapName && mapStart >= exact->address) {
            os << "<" << mapName;
            if (value != mapStart) {
                os << "+0x" << std::hex << std::uppercase << (value - mapStart) << std::dec;
            }
            os << ">";
        } else {
            os << "<" << exact->name << ">";
        }
    } else if (auto nearest = FindNearestTranslatedFunction(value)) {
        if (mapName && mapStart >= nearest->address) {
            os << "<" << mapName;
            if (value != mapStart) {
                os << "+0x" << std::hex << std::uppercase << (value - mapStart) << std::dec;
            }
            os << ">";
        } else {
            os << "<" << nearest->name << "+0x" << std::hex << std::uppercase
               << (value - nearest->address) << std::dec << ">";
        }
    } else if (mapName) {
        os << "<" << mapName << "+0x" << std::hex << std::uppercase
           << (value - mapStart) << std::dec << ">";
    }
    if (auto text = PrintableU32(value)) {
        os << "('" << *text << "')";
    } else if (auto guestString = GuestCStringPreview(value)) {
        os << "(\"" << *guestString << "\")";
    }
}

void PrintFrameTailWords(std::ostream& os, uint32_t previousSp) {
    os << " tail:";
    for (int32_t offset = -0x40; offset <= 0x04; offset += 4) {
        const uint32_t address = previousSp + static_cast<uint32_t>(offset);
        const auto value = ReadGuest32NoThrow(address);
        if (!value) {
            continue;
        }
        os << " " << (offset < 0 ? "-" : "+")
           << std::hex << std::uppercase << std::setw(2) << std::setfill('0')
           << static_cast<uint32_t>(std::abs(offset)) << "=0x" << Hex32(*value);
    }
    os << std::dec << std::setfill(' ');
}

void DumpGuestBackchain(std::ostream& os, const CpuContext* cpu) {
    uint32_t sp = cpu->gpr[1];
    if (sp == 0) {
        return;
    }

    os << "[runtime] Stack backchain:" << std::endl;
    for (int frame = 0; frame < 12; ++frame) {
        const auto previousSp = ReadGuest32NoThrow(sp);
        if (!previousSp || *previousSp == 0) {
            os << "[runtime]   #" << frame << " sp=0x" << Hex32(sp) << " prev=(unmapped)" << std::endl;
            break;
        }

        const uint32_t frameSize = *previousSp - sp;
        os << "[runtime]   #" << frame << " sp=0x" << Hex32(sp)
           << " prev=0x" << Hex32(*previousSp)
           << " size=0x" << std::hex << std::uppercase << frameSize << std::dec;

        if (frameSize <= 0x20000u) {
            if (const auto savedLr = ReadGuest32NoThrow(*previousSp + 4u)) {
                PrintGuestValue(os, "savedLR", *savedLr);
            }
            PrintFrameTailWords(os, *previousSp);
        }
        os << std::endl;

        if (*previousSp <= sp || frameSize > 0x20000u) {
            break;
        }
        sp = *previousSp;
    }
}

void DumpGuestStackHints(std::ostream& os, const CpuContext* cpu) {
    const uint32_t sp = cpu->gpr[1];
    if (sp == 0) {
        return;
    }

    os << "[runtime] Stack words:";
    for (uint32_t offset = 0; offset < 0x40; offset += 4) {
        const auto value = ReadGuest32NoThrow(sp + offset);
        if (!value) {
            break;
        }
        os << " +" << std::hex << std::uppercase << std::setw(2) << std::setfill('0')
           << offset << "=0x" << Hex32(*value);
    }
    os << std::dec << std::setfill(' ') << std::endl;

    int printed = 0;
    for (uint32_t offset = 0; offset < 0x800 && printed < 32; offset += 4) {
        const auto value = ReadGuest32NoThrow(sp + offset);
        if (!value) {
            continue;
        }
        if (!TranslatedFunctionRegistry::FindByAddressPtr(*value) && !FindNearestTranslatedFunction(*value)) {
            continue;
        }
        if (printed == 0) {
            os << "[runtime] Stack code refs:";
        }
        os << " +" << std::hex << std::uppercase << offset << std::dec << ":";
        PrintGuestValue(os, "", *value);
        ++printed;
    }
    if (printed != 0) {
        os << std::endl;
    }
}

void DumpGuestCrashHints(std::ostream& os, const CpuContext* cpu) {
    if (!cpu) {
        return;
    }

    const uint32_t active = RecompMod::CurrentTranslatedExecutionAddress();
    if (active != 0) {
        os << "[runtime] Active translated target: ";
        PrintGuestValue(os, "guest", active);
        os << std::endl;
    }

    os << "[runtime] Guest refs:";
    PrintGuestValue(os, "pc", cpu->pc);
    PrintGuestValue(os, "lr", cpu->lr);
    PrintGuestValue(os, "ctr", cpu->ctr);
    PrintGuestValue(os, "r12", cpu->gpr[12]);
    PrintGuestValue(os, "r3", cpu->gpr[3]);
    PrintGuestValue(os, "r4", cpu->gpr[4]);
    PrintGuestValue(os, "r5", cpu->gpr[5]);
    PrintGuestValue(os, "r15", cpu->gpr[15]);
    PrintGuestValue(os, "r16", cpu->gpr[16]);
    PrintGuestValue(os, "r18", cpu->gpr[18]);
    PrintGuestValue(os, "r26", cpu->gpr[26]);
    PrintGuestValue(os, "r27", cpu->gpr[27]);
    os << std::endl;

    if (active != 0 && active != cpu->pc) {
        os << "[runtime] Note: active translated target differs from ctx->pc; ctx->pc may be stale "
              "without PC tracing."
           << std::endl;
    }

    DumpGuestStackHints(os, cpu);
    DumpGuestBackchain(os, cpu);
}

